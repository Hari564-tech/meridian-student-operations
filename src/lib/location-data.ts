/**
 * Asynchronous location provider service
 * Simulates real API calls with in-memory caching and error resilience
 */
class LocationService {
  private cache = new Map<string, string[]>();

  async getStates(country: string = "India"): Promise<string[]> {
    const key = `states:${country}`;
    if (this.cache.has(key)) return this.cache.get(key)!;

    await new Promise((r) => setTimeout(r, 60)); // Fast simulated latency

    let result: string[] = [];
    if (country === "India") {
      result = [...INDIA_LOCATION_DATA.states].sort();
    } else if (INTERNATIONAL_LOCATION_DATA[country]) {
      result = [...INTERNATIONAL_LOCATION_DATA[country].states].sort();
    } else {
      result = [...INDIA_LOCATION_DATA.states].sort();
    }

    this.cache.set(key, result);
    return result;
  }

  async getDistricts(state: string, country: string = "India"): Promise<string[]> {
    const key = `districts:${country}:${state}`;
    if (this.cache.has(key)) return this.cache.get(key)!;

    await new Promise((r) => setTimeout(r, 60));

    let result: string[] = [];
    if (country === "India") {
      result = INDIA_LOCATION_DATA.districtsByState[state]
        ? [...INDIA_LOCATION_DATA.districtsByState[state]].sort()
        : [];
    } else if (INTERNATIONAL_LOCATION_DATA[country]?.districtsByState[state]) {
      result = [...INTERNATIONAL_LOCATION_DATA[country].districtsByState[state]].sort();
    }

    this.cache.set(key, result);
    return result;
  }

  async getVillagesCities(district: string, state: string, country: string = "India"): Promise<string[]> {
    const key = `villages:${country}:${state}:${district}`;
    if (this.cache.has(key)) return this.cache.get(key)!;

    await new Promise((r) => setTimeout(r, 60));

    let result: string[] = [];
    if (country === "India") {
      if (INDIA_LOCATION_DATA.villagesByDistrict[district]) {
        result = [...INDIA_LOCATION_DATA.villagesByDistrict[district]].sort();
      } else {
        // Fallback default towns for any district not explicitly mapped
        result = [`${district} Town`, `${district} City`, `${district} Rural`, `${district} Central`];
      }
    } else {
      result = [`${district} City`, `${district} Metro`, `${district} Downtown`];
    }

    this.cache.set(key, result);
    return result;
  }
}

export const locationService = new LocationService();
